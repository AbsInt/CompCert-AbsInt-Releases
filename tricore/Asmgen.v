Definition get_sconst9 n : option sconst9 :=
  if is_in_signed_range 9 n then
    Some (mk_sconst9 n)
  else
    None.

Definition get_sconst16 n : option sconst16 :=
  if is_in_signed_range 16 n then
    Some (mk_sconst16 n)
  else
