(** * Abstract syntax *)

(** Like Linear, the Mach language is organized as lists of instructions
  operating over machine registers, with default fall-through behaviour
  and explicit labels and branch instructions.

  The main difference with Linear lies in the instructions used to
  access the activation record.  Mach has three such instructions:
  [Mgetstack] and [Msetstack] to read and write within the activation
  record for the current function, at a given word offset and with a
  given type; and [Mgetparam], to read within the activation record of
  the caller.

  These instructions implement a more concrete view of the activation
  record than the the [Lgetstack] and [Lsetstack] instructions of
  Linear: actual offsets are used instead of abstract stack slots, and the
  distinction between the caller's frame and the callee's frame is
  made explicit. *)

Definition label := positive.

Inductive instruction: Type :=
  | Mgetstack: ptrofs -> typ -> (rpair mreg) -> instruction
  | Msetstack: (rpair mreg) -> ptrofs -> typ -> instruction
  | Msavecallee: Z -> list (rpair mreg) -> instruction
  | Mrestorecallee: Z -> list (rpair mreg) -> instruction
  | Mgetparam: ptrofs -> typ -> (rpair mreg) -> instruction
  | Mop: operation -> list (rpair mreg) -> (rpair mreg) -> instruction
  | Mload: memory_chunk -> addressing -> list mreg -> (rpair mreg) -> instruction
  | Mstore: memory_chunk -> addressing -> list mreg -> (rpair mreg) -> instruction
  | Mcall: signature -> mreg + ident -> instruction
  | Mtailcall: signature -> mreg + ident -> instruction
  | Mbuiltin: external_function -> list (builtin_arg (rpair mreg)) -> builtin_res (rpair mreg) -> instruction
  | Mlabel: label -> instruction
  | Mgoto: label -> instruction
  | Mcond: condition -> list (rpair mreg) -> label -> instruction
  | Mjumptable: mreg -> list label -> instruction
  | Mreturn: instruction.

Definition code := list instruction.

Record function: Type := mkfunction
  { fn_sig: signature;
    fn_code: code;
    fn_stacksize: Z;
    fn_link_ofs: ptrofs;
    fn_retaddr_ofs: ptrofs }.

Definition fundef := AST.fundef function.

Definition program := AST.program fundef unit.

Definition funsig (fd: fundef) :=
  match fd with
  | Internal f => fn_sig f
  | External ef => ef_sig ef
  end.

Definition genv := Genv.t fundef unit.

(** * Operational semantics *)

(** The semantics for Mach is close to that of [Linear]: they differ only
  on the interpretation of stack slot accesses.  In Mach, these
  accesses are interpreted as memory accesses relative to the
  stack pointer.  More precisely:
- [Mgetstack ofs ty r] is a memory load at offset [ofs * 4] relative
  to the stack pointer.
- [Msetstack r ofs ty] is a memory store at offset [ofs * 4] relative
  to the stack pointer.
- [Mgetparam ofs ty r] is a memory load at offset [ofs * 4]
  relative to the pointer found at offset 0 from the stack pointer.
  The semantics maintain a linked structure of activation records,
  with the current record containing a pointer to the record of the
  caller function at offset 0.

In addition to this linking of activation records, the
semantics also make provisions for storing a back link at offset
[f.(fn_link_ofs)] from the stack pointer, and a return address at
offset [f.(fn_retaddr_ofs)].  The latter stack location will be used
by the Asm code generated by [Asmgen] to save the return address into
the caller at the beginning of a function, then restore it and jump to
it at the end of a function.  The Mach concrete semantics does not
attach any particular meaning to the pointer stored in this reserved
location, but makes sure that it is preserved during execution of a
function.  The [return_address_offset] parameter is used to guess the
value of the return address that the Asm code generated later will
store in the reserved location.
*)

Definition load_stack (m: mem) (sp: val) (ty: typ) (ofs: ptrofs) :=
  Mem.loadv (chunk_of_type ty) m (Val.offset_ptr sp ofs).

Definition store_stack (m: mem) (sp: val) (ty: typ) (ofs: ptrofs) (v: val) :=
  Mem.storev (chunk_of_type ty) m (Val.offset_ptr sp ofs) v.

Module RegEq.
  Definition t := mreg.
  Definition eq := mreg_eq.
End RegEq.

Module Regmap := EMap(RegEq).

Definition regset := Regmap.t val.

Notation "a ## b" := (List.map a b) (at level 1).
Notation "a # b <- c" := (Regmap.set b c a) (at level 1, b at next level).

Fixpoint undef_regs (rl: list mreg) (rs: regset) {struct rl} : regset :=
  match rl with
  | nil => rs
  | r1 :: rl' => Regmap.set r1 Vundef (undef_regs rl' rs)
  end.

Lemma undef_regs_other:
  forall r rl rs, ~In r rl -> undef_regs rl rs r = rs r.
Proof.
  induction rl; simpl; intros. auto. rewrite Regmap.gso. apply IHrl. intuition. intuition.
Qed.

Lemma undef_regs_same:
  forall r rl rs, In r rl -> undef_regs rl rs r = Vundef.
Proof.
  induction rl; simpl; intros. tauto.
  destruct H. subst a. apply Regmap.gss.
  unfold Regmap.set. destruct (RegEq.eq r a); auto.
Qed.

Definition pre_return_regs (caller callee: regset) : regset :=
  fun r => if is_callee_save r then caller r else callee r.

Definition undef_callee_may_modify_regs (rs: regset) : regset :=
  fun r => if is_modifiable_by_callee r then Vundef else rs r.

Definition restore_auto_save_regs (caller rs: regset) : regset :=
  fun r => if is_auto_save r then caller r else rs r.

Definition return_regs (caller callee: regset) : regset :=
  restore_auto_save_regs caller (pre_return_regs caller callee).

Definition external_call_regs (caller rs: regset) : regset :=
  restore_auto_save_regs caller (undef_callee_may_modify_regs rs).

Definition tailcall_regs (caller rs: regset) : regset :=
  pre_return_regs caller rs.

Definition set_pair (p: rpair mreg) (v: val) (rs: regset) : regset :=
  match p with
  | One r => rs#r <- v
  | Two rhi rlo => rs#rhi <- (Val.hiword v) #rlo <- (Val.loword v)
  end.

Definition get_pair (p: rpair mreg) (rs: regset) : val :=
  match p with
  | One r => rs r
  | Two r1 r2 => Val.combine (rs r1) (rs r2)
  end.

Definition get_pairs (l: list (rpair mreg)) (rs: regset) : list val :=
  map (fun q => get_pair q rs) l.

Fixpoint set_res (res: builtin_res (rpair mreg)) (v: val) (rs: regset) : regset :=
  match res with
  | BR p => set_pair p v rs
  | BR_none => rs
  | BR_splitlong hi lo => set_res lo (Val.lowordoflong v) (set_res hi (Val.hiwordoflong v) rs)
  end.

Definition is_label (lbl: label) (instr: instruction) : bool :=
  match instr with
  | Mlabel lbl' => if peq lbl lbl' then true else false
  | _ => false
  end.

Lemma is_label_correct:
  forall lbl instr,
  if is_label lbl instr then instr = Mlabel lbl else instr <> Mlabel lbl.
Proof.
  intros.  destruct instr; simpl; try discriminate.
  case (peq lbl l); intro; congruence.
Qed.

Fixpoint find_label (lbl: label) (c: code) {struct c} : option code :=
  match c with
  | nil => None
  | i1 :: il => if is_label lbl i1 then Some il else find_label lbl il
  end.

Lemma find_label_tail:
  forall lbl c c', find_label lbl c = Some c' -> is_tail c' c.
Proof.
  induction c; simpl; intros. discriminate.
  destruct (is_label lbl a). inv H. auto with coqlib. eauto with coqlib.
Qed.

Lemma find_label_incl:
  forall lbl c c', find_label lbl c = Some c' -> incl c' c.
Proof.
  intros; red; intros. eapply is_tail_incl; eauto. eapply find_label_tail; eauto.
Qed.

Definition save_callee_pair (m: mem) (sp: val) (ofs: Z) (p:rpair mreg) (rs: regset) :=
  match p with
  | One r => store_stack m sp (mreg_type r) (Ptrofs.repr ofs) (rs r)
  | Two r1 r2 => let hireg := if Archi.big_endian then r2 else r1 in
                let loreg := if Archi.big_endian then r1 else r2 in
                match store_stack m sp (mreg_type loreg) (Ptrofs.repr ofs) (rs loreg) with
                | Some m' => let sz := AST.typesize (mreg_type loreg) in
                                      store_stack m' sp (mreg_type hireg) (Ptrofs.add (Ptrofs.repr ofs)  (Ptrofs.repr sz)) (rs hireg)
                | None => None
                end
  end.

Definition restore_callee_pair (m: mem) (sp: val) (ofs: Z) (p: rpair mreg) (rs: regset) :=
  match p with
  | One r => match load_stack m sp (mreg_type r) (Ptrofs.repr ofs) with
            | Some v => Some (rs # r <- v)
            | None => None
            end
  | Two r1 r2 => let hireg := if Archi.big_endian then r2 else r1 in
                let loreg := if Archi.big_endian then r1 else r2 in
                let sz := AST.typesize (mreg_type loreg) in
                match load_stack m sp (mreg_type loreg) (Ptrofs.repr ofs),
                      load_stack m sp (mreg_type hireg) (Ptrofs.add (Ptrofs.repr ofs) (Ptrofs.repr sz)) with
                | Some v1, Some v2 => Some (rs # hireg <- v2) # loreg <- v1
                | _, _ => None
                end
  end.

Fixpoint store_stack_rpairs (m: mem) (sp: val) (ofs: Z) (l: list (rpair mreg)) (rs: regset) :=
  match l with
  | p :: l =>
      let sz := compute_size p in
      let ofs1 := align ofs sz in
      match save_callee_pair m sp ofs1 p rs with
      | Some m' => store_stack_rpairs m' sp (ofs1 + sz) l rs
      | _ => None
      end
  | nil => Some m
  end.

Fixpoint load_stack_rpairs (m: mem) (sp: val) (ofs: Z) (l: list (rpair mreg)) (rs: regset) :=
  match l with
  | p :: l =>
      let sz := compute_size p in
      let ofs1 := align ofs sz in
      match restore_callee_pair m sp ofs1 p rs with
      | Some rs' => load_stack_rpairs m sp (ofs1 + sz) l rs'
      | _ => None
      end
  | nil => Some rs
  end.

Definition destroyed_by_setstack_pair p :=
  match p with
  | One r => destroyed_by_setstack (mreg_type r)
  | Two rhi rlo => destroyed_by_setstack (mreg_type rhi) ++ (destroyed_by_setstack (mreg_type rlo))
  end.

